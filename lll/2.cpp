#include <iostream>
using namespace std;

int main() {
    int N, M;
    cin >> N >> M;

    int points[100][100]; // Баллы, которые изначально лежат в клетках
    int sum[100][100];    // Тут будем копить лучшую сумму

    // Шаг 1. Читаем карту с баллами
    for (int i = 0; i < N; i++) {
        for (int j = 0; j < M; j++) {
            cin >> points[i][j];
        }
    }

    //Заполняем таблицу сумм, идя слева-направо, сверху-вниз
    for (int i = 0; i < N; i++) {
        for (int j = 0; j < M; j++) {
            // Сначала ставим просто балл этой клетки
            sum[i][j] = points[i][j];

            // Если мы не в самом начале...
            if (i > 0 || j > 0) {
                int best_before = -1000000; // Очень плохой вариант, чтобы любое другое число его побило

                // Можно было прийти сверху?
                if (i > 0 && sum[i - 1][j] > best_before) {
                    best_before = sum[i - 1][j];
                }

                // Можно было прийти слева?
                if (j > 0 && sum[i][j - 1] > best_before) {
                    best_before = sum[i][j - 1];
                }

                // Прибавляем лучший из предыдущих вариантов к текущему баллу
                sum[i][j] = best_before + points[i][j];
            }
        }
    }

    // Ответ — это то, что накопилось в правом нижнем углу
    cout << sum[N - 1][M - 1] << endl;

    return 0;
}
